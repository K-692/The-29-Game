// Bundles the Supabase Edge Function (and the shared game engine it imports)
// into one ESM file that can be deployed as-is.
import { build } from 'esbuild';

await build({
  entryPoints: ['supabase/functions/game/index.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: 'supabase/functions/game/dist/index.js',
  legalComments: 'none',
  minify: true,
  banner: { js: '// Generated by scripts/build-function.mjs — do not edit.' },
});
console.log('Built supabase/functions/game/dist/index.js');
